// Package ezclassify provides a Go SDK for the EzClassify REST API.
//
// The SDK is HTTP-only. It contains no classification engine, content, license,
// or deployment configuration; operations are delegated to a running
// EzClassify REST API instance.
//
// # Quick start
//
// Start the Cedar Valley replay server (it needs Node.js 22 or newer, and the
// client itself does not):
//
//	npx @ezclassify/conformance-server --scenario cedar-valley --port 4010
//
// Then connect the client to it and process a recorded marking:
//
//	cx := ezclassify.Connect("http://127.0.0.1:4010", "cedar-valley", "1.0.0")
//	resp, err := cx.Scheme.Process(ctx,
//	    ezclassify.CtxSchemeProcessRequest{Input: "INTERNAL"})
//	if err != nil { log.Fatal(err) }
//	fmt.Println(resp.Result.Rendered) // => "INTERNAL"
//
// The server replays recorded answers for a finite set of requests; anything
// else gets a 501 diagnostic. To use a runtime, change the base URL and supply
// credentials:
//
//	client := ezclassify.New("https://runtime.example.com",
//	    ezclassify.WithCredentials(ezclassify.RestClientCredentials{
//	        AccessToken: accessToken, ContextToken: contextToken}))
//	cx := ezclassify.ConnectWith(client, "your-context-id", "")
//
// The wire layer is generated by oapi-codegen from the OpenAPI spec vendored
// at spec/openapi.yaml, and its types are re-exported here as aliases,
// so internal/api never appears in caller code.
//
// # Context-bound operations
//
// Use [ConnectWith] to bind one published Context. Omit the version, by
// passing "", to let the server choose: the Context token's default version,
// or the newest published. "latest" means the same:
//
//	cx := ezclassify.ConnectWith(client, "my-ctx", "")
//	resp, err := cx.Scheme.Process(ctx,
//	    ezclassify.CtxSchemeProcessRequest{Input: "MARKING"})
//
// The version the server chose is reported by
// [EzClassifyContext.ResolvedVersion], read from the
// X-EzClassify-Resolved-Version response header.
//
// # Reading and writing markings
//
// [CtxScheme.Validate] is the reader's call: code that displays a marking,
// gates on it, stores it, or hands its facts to an access check sends the text
// or the stated facts and gets a [ValidateResult]. [CtxScheme.Process] is the
// author's call: it answers everything validate does, settled the same way, plus
// the corrections, proven fix paths, the renders named in Outputs, and the
// picker options named in SuggestFor, as a [ProcessResult]. Valid says whether a
// marking stands once settled and InputWasValid whether it was right as
// written; both mean the same on every result. [CtxScheme.Explain] returns the
// trace of how the server settled a marking.
//
// # Scheme views
//
// [CtxScheme.Categories], [CtxScheme.Concepts] and [CtxScheme.Formats] return
// [CategoryView], [ConceptView] and [FormatView] values, the same views a
// local engine's scheme view carries. [CtxScheme.LabelPresets] lists the
// [LabelPresetView] entries of the Context's primary scheme, and
// [CtxScheme.ApplyPreset] expands one into a marking written in the
// request's OutputFormat.
//
// # Notices
//
// Every result that describes a marking carries the notices the scheme attaches
// to its concepts. [ValidateResult], [ProcessResult] and [AggregateResult] have
// a Notices field, and each scan match reaches the same list through its
// validate result:
//
//	for _, n := range resp.Result.Notices {
//	    fmt.Println(n.ConceptName, n.Text, n.Required)
//	}
//
// The field is always present and is empty when the marking carries none.
// [CtxScheme.Notices] collects the same list for assertions the caller
// assembled some other way; a marking this SDK already processed does not need
// it.
//
// # Errors
//
// The composed-context layer ([EzClassifyContext] operation groups and
// [EzClassifyContext.Resolve]) returns typed errors for non-2xx responses. Every
// HTTP failure is an [APIError] carrying the operation name, the status code,
// and the raw response body. A 404 is reported as [ContextNotFoundError] unless
// the server identifies an unmatched route or a missing concept. Those resource
// errors remain plain APIError values; ContextNotFoundError wraps the APIError:
//
//	_, err := cx.Scheme.Process(ctx, req)
//	var notFound *ezclassify.ContextNotFoundError
//	if errors.As(err, &notFound) {
//	    // notFound.ContextID does not exist or is not visible
//	}
//	var apiErr *ezclassify.APIError
//	if errors.As(err, &apiErr) {
//	    // any non-2xx, including 404: apiErr.StatusCode, apiErr.Body
//	}
//
// A 429 from the rate limiter, which can answer any operation, sets
// [APIError.RetryAfter] to the wait the server asks for. The client never
// retries or sleeps itself; a caller that waits should bound the wait.
//
// Transport failures and JSON decode failures propagate as-is, not as
// APIError.
