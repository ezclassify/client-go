// Command apisurface dumps the exported API surface of the root SDK package
// (excluding internal/, examples/, and tool packages) and diffs it against
// the committed golden in api/1.0.txt.
//
// The surface is locked at 1.0: adding, removing, or changing any exported
// name or signature is a breaking-contract event and must be a reviewed,
// deliberate act. CI runs this command in check mode on every push; after an
// approved API review, regenerate the golden with `make api-surface` and
// commit it together with the code change.
//
// Output format follows the style of Go's own api/go1.txt: one sorted,
// whitespace-normalized line per exported feature, with doc comments and
// parameter names stripped so the dump is deterministic and rename-of-
// argument noise free. Constant and variable values are intentionally
// omitted: stamped values (for example the spec version) are bumped by the
// release automation and are not part of the shape contract.
//
// The wire DTOs aliased from internal/api are recorded here as
// aliases only, not expanded field by field. Their definitions are generated
// from spec/openapi.yaml and are already frozen by the spec-hash and
// regen gates in CI, so expanding them would only duplicate that gate.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const goldenPath = "api/1.0.txt"

const header = `# EzClassify Go SDK public API surface, locked at 1.0.
# One line per exported feature of the root ezclassify package (internal/ excluded).
# Generated by tools/apisurface. Do not edit by hand.
# Regenerate deliberately after an approved API review: make api-surface
`

func main() {
	write := flag.Bool("write", false, "regenerate "+goldenPath+" instead of checking against it")
	flag.Parse()

	current, err := surface()
	if err != nil {
		fmt.Fprintf(os.Stderr, "apisurface: %v\n", err)
		os.Exit(1)
	}

	if *write {
		if err := os.MkdirAll(filepath.Dir(goldenPath), 0o755); err != nil {
			fmt.Fprintf(os.Stderr, "apisurface: %v\n", err)
			os.Exit(1)
		}
		if err := os.WriteFile(goldenPath, []byte(current), 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "apisurface: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("apisurface: wrote %s\n", goldenPath)
		return
	}

	golden, err := os.ReadFile(goldenPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "apisurface: cannot read golden %s: %v\n", goldenPath, err)
		fmt.Fprintln(os.Stderr, "Run 'make api-surface' from the repo root to create it.")
		os.Exit(1)
	}

	if string(golden) == current {
		fmt.Printf("apisurface: OK, exported surface matches %s\n", goldenPath)
		return
	}

	removed, added := diffLines(featureLines(string(golden)), featureLines(current))
	fmt.Fprintf(os.Stderr, `ERROR: exported API surface does not match the 1.0-locked golden (%s).

The public surface of this SDK is a frozen contract as of 1.0. Any addition,
removal, or signature change to an exported name must go through an API
review. If this change was reviewed and is deliberate, regenerate the golden
and commit it together with the code change:

    make api-surface

`, goldenPath)
	for _, l := range removed {
		fmt.Fprintf(os.Stderr, "  removed: %s\n", l)
	}
	for _, l := range added {
		fmt.Fprintf(os.Stderr, "  added:   %s\n", l)
	}
	if len(removed) == 0 && len(added) == 0 {
		// Same feature set but different bytes (header edit or stray line).
		fmt.Fprintf(os.Stderr, "  golden file text differs from generated output; run 'make api-surface'\n")
	}
	os.Exit(1)
}

// surface builds the full golden file content: header plus one sorted line
// per exported feature.
func surface() (string, error) {
	dirs, err := packageDirs(".")
	if err != nil {
		return "", err
	}
	if len(dirs) == 0 {
		return "", fmt.Errorf("no root package found (run from the repo root)")
	}

	var lines []string
	for _, dir := range dirs {
		pkgLines, err := packageSurface(dir)
		if err != nil {
			return "", err
		}
		lines = append(lines, pkgLines...)
	}
	sort.Strings(lines)
	return header + strings.Join(lines, "\n") + "\n", nil
}

// packageDirs lists directories under root that contain non-test Go files,
// skipping internal packages (not importable, so not public surface) and the
// non-SDK trees: vendored sources, runnable examples, repo tooling, and
// scripts. Hidden directories (.git, .github) are skipped as well.
func packageDirs(root string) ([]string, error) {
	skip := map[string]bool{
		"vendor":   true,
		"internal": true,
		"examples": true,
		"tools":    true,
		"scripts":  true,
	}
	var dirs []string
	seen := map[string]bool{}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if path != root && (skip[d.Name()] || strings.HasPrefix(d.Name(), ".")) {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasSuffix(path, ".go") && !strings.HasSuffix(path, "_test.go") {
			// Dedupe with a set, not a last-element check: WalkDir interleaves
			// subdirectories lexically between a directory's files, so the
			// same directory can reappear after its subpackages.
			dir := filepath.Dir(path)
			if !seen[dir] {
				seen[dir] = true
				dirs = append(dirs, dir)
			}
		}
		return nil
	})
	return dirs, err
}

// packageSurface parses every non-test file in dir and returns one line per
// exported declaration, prefixed with the package path.
func packageSurface(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	var lines []string
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		// Comments are not requested from the parser, so doc comments never
		// reach the printed output.
		file, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		// Label the root package by its package name rather than the "."
		// directory path, so golden lines read "ezclassify, ...".
		pkg := filepath.ToSlash(dir)
		if pkg == "." {
			pkg = "ezclassify"
		}
		for _, decl := range file.Decls {
			lines = append(lines, declLines(pkg, fset, decl)...)
		}
	}
	return lines, nil
}

func declLines(pkg string, fset *token.FileSet, decl ast.Decl) []string {
	var lines []string
	switch d := decl.(type) {
	case *ast.FuncDecl:
		if !d.Name.IsExported() {
			return nil
		}
		if d.Recv == nil {
			lines = append(lines, pkg+", func "+d.Name.Name+typeParamList(fset, d.Type.TypeParams)+signature(fset, d.Type))
			return lines
		}
		recv := d.Recv.List[0].Type
		if !ast.IsExported(receiverBase(recv)) {
			return nil
		}
		lines = append(lines, pkg+", method ("+exprString(fset, recv)+") "+d.Name.Name+signature(fset, d.Type))
	case *ast.GenDecl:
		switch d.Tok {
		case token.CONST, token.VAR:
			kw := "const"
			if d.Tok == token.VAR {
				kw = "var"
			}
			for _, spec := range d.Specs {
				vs, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				typ := ""
				if vs.Type != nil {
					typ = " " + exprString(fset, vs.Type)
				}
				for _, n := range vs.Names {
					if n.IsExported() {
						lines = append(lines, pkg+", "+kw+" "+n.Name+typ)
					}
				}
			}
		case token.TYPE:
			for _, spec := range d.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok || !ts.Name.IsExported() {
					continue
				}
				lines = append(lines, typeLines(pkg, fset, ts)...)
			}
		}
	}
	return lines
}

func typeLines(pkg string, fset *token.FileSet, ts *ast.TypeSpec) []string {
	name := ts.Name.Name + typeParamList(fset, ts.TypeParams)
	if ts.Assign.IsValid() {
		return []string{pkg + ", type " + name + " = " + exprString(fset, ts.Type)}
	}
	switch t := ts.Type.(type) {
	case *ast.StructType:
		head := pkg + ", type " + name + " struct"
		lines := []string{head}
		for _, f := range t.Fields.List {
			tag := ""
			if f.Tag != nil {
				tag = " " + f.Tag.Value
			}
			if len(f.Names) == 0 {
				// Embedded field: promoted methods and fields are public
				// surface, so the embedding itself is locked.
				if !ast.IsExported(receiverBase(f.Type)) {
					continue
				}
				lines = append(lines, head+", embedded "+exprString(fset, f.Type)+tag)
				continue
			}
			for _, n := range f.Names {
				if n.IsExported() {
					lines = append(lines, head+", "+n.Name+" "+exprString(fset, f.Type)+tag)
				}
			}
		}
		return lines
	case *ast.InterfaceType:
		head := pkg + ", type " + name + " interface"
		lines := []string{head}
		for _, m := range t.Methods.List {
			if len(m.Names) == 0 {
				lines = append(lines, head+", embedded "+exprString(fset, m.Type))
				continue
			}
			if !m.Names[0].IsExported() {
				continue
			}
			if ft, ok := m.Type.(*ast.FuncType); ok {
				lines = append(lines, head+", "+m.Names[0].Name+signature(fset, ft))
			}
		}
		return lines
	default:
		return []string{pkg + ", type " + name + " " + exprString(fset, ts.Type)}
	}
}

// typeParamList renders a generic declaration's type-parameter list, e.g.
// "[T any]", or "" for a non-generic declaration. Parameter names are kept
// (unlike value parameters, they are referenced by the signature lines) and
// constraints shape what callers may instantiate, so both are locked surface.
func typeParamList(fset *token.FileSet, tp *ast.FieldList) string {
	if tp == nil || len(tp.List) == 0 {
		return ""
	}
	var parts []string
	for _, f := range tp.List {
		names := make([]string, len(f.Names))
		for i, n := range f.Names {
			names[i] = n.Name
		}
		parts = append(parts, strings.Join(names, ", ")+" "+exprString(fset, f.Type))
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// signature renders a func type with parameter and result names stripped, so
// renaming an argument is not flagged as a surface change.
func signature(fset *token.FileSet, ft *ast.FuncType) string {
	params := fieldTypes(fset, ft.Params)
	out := "(" + strings.Join(params, ", ") + ")"
	results := fieldTypes(fset, ft.Results)
	switch len(results) {
	case 0:
	case 1:
		out += " " + results[0]
	default:
		out += " (" + strings.Join(results, ", ") + ")"
	}
	return out
}

func fieldTypes(fset *token.FileSet, fl *ast.FieldList) []string {
	if fl == nil {
		return nil
	}
	var out []string
	for _, f := range fl.List {
		t := exprString(fset, f.Type)
		n := len(f.Names)
		if n == 0 {
			n = 1
		}
		for i := 0; i < n; i++ {
			out = append(out, t)
		}
	}
	return out
}

// receiverBase returns the identifier a receiver or embedded-field type
// ultimately names, for the exported-or-not decision.
func receiverBase(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.StarExpr:
		return receiverBase(t.X)
	case *ast.SelectorExpr:
		return t.Sel.Name
	case *ast.IndexExpr:
		return receiverBase(t.X)
	case *ast.IndexListExpr:
		return receiverBase(t.X)
	case *ast.Ident:
		return t.Name
	default:
		return ""
	}
}

func exprString(fset *token.FileSet, e ast.Expr) string {
	var buf bytes.Buffer
	if err := printer.Fprint(&buf, fset, e); err != nil {
		return "<unprintable>"
	}
	return strings.Join(strings.Fields(buf.String()), " ")
}

// featureLines strips header comments and blanks, leaving the sorted feature
// set for diffing.
func featureLines(s string) []string {
	var out []string
	for _, l := range strings.Split(s, "\n") {
		if l == "" || strings.HasPrefix(l, "#") {
			continue
		}
		out = append(out, l)
	}
	sort.Strings(out)
	return out
}

// diffLines walks two sorted line sets and returns what is only in the golden
// (removed) and only in the current surface (added).
func diffLines(golden, current []string) (removed, added []string) {
	i, j := 0, 0
	for i < len(golden) && j < len(current) {
		switch {
		case golden[i] == current[j]:
			i++
			j++
		case golden[i] < current[j]:
			removed = append(removed, golden[i])
			i++
		default:
			added = append(added, current[j])
			j++
		}
	}
	removed = append(removed, golden[i:]...)
	added = append(added, current[j:]...)
	return removed, added
}
