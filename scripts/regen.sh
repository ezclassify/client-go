#!/usr/bin/env bash
# Regenerate internal/api/api.gen.go from the canonical
# vendored OpenAPI spec in spec/openapi.yaml.
# Run from the repo root: bash scripts/regen.sh
set -euo pipefail

SPEC="spec/openapi.yaml"
OUTFILE="internal/api/api.gen.go"
CODEGEN_DIR=$(mktemp -d)
trap 'rm -rf "${CODEGEN_DIR}"' EXIT
CODEGEN_SPEC="${CODEGEN_DIR}/openapi.yaml"

# oapi-codegen version pinned here and in generate.go. Bump both together.
GEN_VER="v2.8.0"
GEN_HASH="h1:s4hxMxuqtR8jPzXkBTtFwY/SBuj3gEAYikmbBSdtLMM="

SPEC_SHA=$(sha256sum "${SPEC}" | awk '{print $1}')

BANNER="// Code generated from openapi.yaml@${SPEC_SHA} by oapi-codegen@${GEN_VER}@${GEN_HASH}. DO NOT EDIT."

# Pinned oapi-codegen reads OpenAPI 3.0. Convert only reviewed 3.1 schema
# unions in a temporary input; the canonical mirror and banner stay 3.1.
go run ./scripts/codegen-spec "${SPEC}" "${CODEGEN_SPEC}"

# The isolated native tool module pins patched generator dependencies without
# adding build-only packages to the SDK runtime module.
go run -mod=readonly -modfile=tools/codegen/go.mod \
  github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen \
  -config oapi-codegen.yaml "${CODEGEN_SPEC}"

# Replace oapi-codegen's 3-line header (// Package..., //, // Code generated by...)
# with our 2-line header (banner, // Package...).
PKG_DOC=$(sed -n '1p' "${OUTFILE}")
{
  echo "${BANNER}"
  echo "${PKG_DOC}"
  tail -n +4 "${OUTFILE}"
} > "${OUTFILE}.tmp"
mv "${OUTFILE}.tmp" "${OUTFILE}"

echo "Regenerated ${OUTFILE}"
echo "  spec-sha:  ${SPEC_SHA}"
echo "  gen-hash:  ${GEN_HASH}"
